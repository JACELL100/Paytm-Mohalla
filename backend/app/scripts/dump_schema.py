"""Write supabase/schema.sql (Postgres DDL) from the SQLAlchemy models, so the two never drift.

    python -m app.scripts.dump_schema
"""

from __future__ import annotations

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from .. import models  # noqa: F401
from ..core.config import REPO_ROOT
from ..core.db import Base

HEADER = """-- Mohalla schema for Supabase Postgres. GENERATED by `python -m app.scripts.dump_schema` from backend/app/models.py.
-- Apply in the Supabase SQL editor (or psql), then supabase/rls.sql. Alternatively `python -m app.scripts.init_db`
-- with DATABASE_URL pointing at Supabase creates the same tables.
-- Money is integer paise. profiles.id = auth.users.id for real users (no FK, so seeded demo profiles also work).

"""


def render() -> str:
    d = postgresql.dialect()
    parts = [HEADER]
    for t in Base.metadata.sorted_tables:
        ddl = str(CreateTable(t, if_not_exists=True).compile(dialect=d)).strip()
        parts.append(ddl + ";\n")
        for ix in sorted(t.indexes, key=lambda i: i.name or ""):
            parts.append(str(CreateIndex(ix, if_not_exists=True).compile(dialect=d)).strip() + ";\n")
        parts.append("\n")
    return "".join(parts)


def main() -> None:
    out = REPO_ROOT / "supabase" / "schema.sql"
    out.parent.mkdir(exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
